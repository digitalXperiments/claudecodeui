import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';

import { parse } from 'acorn';

const htmlPath = path.resolve('public/mweb/index.html');

test('mweb expansion surfaces stay Safari 9 / ES5 compatible', async () => {
  const html = await readFile(htmlPath, 'utf8');
  const match = html.match(/<script>\s*([\s\S]*?)<\/script>/i);
  assert.ok(match, 'mweb must contain its inline application script');
  const source = match[1];
  parse(source, { ecmaVersion: 5 });
  assert.doesNotMatch(source, /\bfetch\s*\(/);
  assert.doesNotMatch(source, /\bPromise\b/);
  assert.doesNotMatch(source, /=>/);
  assert.match(html, /apple-mobile-web-app-capable/);
  assert.match(html, /id="btnReviewFromCategories"[^>]*>MC</);
  assert.match(html, /id="screenReview"/);
  assert.doesNotMatch(html, /data-tool="relay"/);
  assert.doesNotMatch(html, /id="screenMore"/);
  assert.doesNotMatch(source, /\/api\/agent-relay\/jobs/);
  assert.doesNotMatch(source, /\/api\/kanban\/global/);
  assert.doesNotMatch(source, /\/api\/notifications\/inbox/);
  assert.match(source, /X-Refreshed-Token/);
  assert.match(source, /scheduleWsReconnect/);
  assert.match(source, /protocol_error/);
  assert.match(source, /state\.streamingText \+= deltaText/);
  assert.match(source, /\/api\/mission-control\/items/);
  assert.match(source, /performReviewAction/);
  assert.doesNotMatch(html, /Continue last/);
  assert.match(html, /class="sessionSetup"/);
  assert.match(html, /float:\s*left/);
  assert.doesNotMatch(html, /display:\s*grid/);
  assert.doesNotMatch(html, /\bgap\s*:/);
  assert.match(source, /setSessionsLoadMoreBusy\(true\)/);
  assert.match(source, /btnSpinner/);
  assert.match(html, /theme-paper/);
  assert.match(html, /theme-dusk/);
  assert.match(html, /theme-fog/);
  assert.match(html, /theme-ink/);
  assert.match(html, /id="themePicker"/);
  assert.match(html, /id="logoutConfirm"/);
  assert.match(source, /function confirmLogout/);
  assert.match(source, /btnLogoutCategories'\)\.onclick = confirmLogout/);
  assert.doesNotMatch(html, /theme-light/);
  assert.match(source, /cloudcli_mweb_theme/);
  assert.match(source, /normalizeTheme/);
  assert.match(source, /theme === 'light' \|\| theme === 'paper'/);
  assert.match(source, /theme === 'dark' \|\| theme === 'dusk'/);
  assert.match(source, /openThemePicker/);
  assert.match(source, /chooseTheme/);
  assert.match(source, /chooseFont/);
  assert.match(html, /id="typeSizeSm"/);
  assert.match(html, /id="typeSizeMd"/);
  assert.match(html, /id="typeSizeLg"/);
  assert.match(source, /cloudcli_mweb_font/);
  assert.match(source, /cloudcli_mweb_drafts/);
  assert.match(source, /saveCurrentDraft/);
  assert.match(source, /onNewSessionClick/);
  assert.match(html, /id="btnCancelNewSession"/);
  assert.match(html, /\.sessionSetup \.setupGrid \{ display: none; \}/);
  assert.doesNotMatch(source, /current === 'paper' \? 'dusk' : 'paper'/);
  assert.doesNotMatch(html, /#2a2a2a/);
});
