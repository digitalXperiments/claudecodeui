const CLAUDE_MD = `${marker()}

# Article studio

This directory is a writing workspace, not a codebase. Everything here exists to
turn things I actually built into articles people want to read on x.com.

## Who is writing

Me: a solo builder shipping CloudCLI — a multi-agent CLI workspace — mostly at
night and on weekends. Read \`voice/voice.md\` before drafting anything.

## The rule that matters most

**Write the story of building it, not the documentation of what was built.**

A reader clicks because they recognise a situation, not because they need an
API reference. The technical detail is what makes the story credible — it is
never the reason to keep reading.

Test for any draft: could this have been written by someone who read the repo
but never did the work? If yes, it fails. Put back the decisions, the dead
ends, the moment it broke, the thing I believed that turned out to be wrong.

## Files here

- \`voice/voice.md\` — how I sound. Non-negotiable.
- \`patterns/patterns.md\` — title and structure patterns distilled from articles
  that actually performed. Regenerated by the "Swipe Digest" Mission Control
  section from my Obsidian \`Clippings/\` folder.
- \`story-bank.md\` — candidate stories, and which are already used.
- \`drafts/\`, \`published/\` — working copies. Mission Control is the source of
  truth for a draft; these are for me to scribble in.

## Skills

Invoke these by name — they are in \`.claude/skills/\`:

- \`story-angles\` — turn a build into a story with an arc
- \`hooks-and-titles\` — the title and the first three lines
- \`article-structure\` — how the middle holds together
- \`fact-grounding\` — get the real details without going dry
- \`swipe-analysis\` — distill saved articles into reusable patterns

## Facts come from outside this folder

The build history lives in Obsidian under \`Projects/CloudCLI/\` (Decisions,
Entities, Sessions) and in the repo at \`~/Development/cloudcli-fork\`. Use the
obsidian tools for what happened and why. Never invent a feature, a number, or
a date. If I did not build it, it does not go in the article.
`;

const VOICE_MD = `${marker()}

# Voice

## Who I am on the page

A solo builder shipping in public. I am not a company, not a thought leader,
and not writing a tutorial. I am telling you what I built this week and what it
cost me.

## Person and tense

- First person singular. "I built", "I assumed", "I was wrong".
- Past tense for the story. Present tense for the lesson.
- Address the reader as "you" only when handing over the lesson.

## Register

Plain, fast, a little dry. The humour comes from honesty about how dumb the bug
was, never from jokes. Short sentences. Paragraphs of one to three lines —
this gets read on a phone.

## Things I do

- Admit the wrong assumption before revealing the right one.
- Name real things: file paths, error strings, providers, hours lost.
- Say how long something took, when I know.
- End on the lesson or an honest open question. Never a summary.

## Things I never do

- "Game-changer", "unlock", "leverage" as a verb, "delve", "seamless",
  "robust", "supercharge", "journey", "excited to share", "in today's
  fast-paced world".
- Emoji in headings. Emoji as bullet points.
- Rhetorical question openers. "Ever wondered why…?"
- Fake numbers. No "3x faster" unless I measured it and it is written down.
- Engagement bait: "Thoughts?", "Who else?", "Drop a comment".
- LinkedIn cadence: one-line paragraphs stacked for drama.
- Claiming something is easy. If it were easy there would be no article.

## Calibration

If a sentence would survive unchanged in a product changelog, it does not
belong in the article. If it could only have been written by the person who
did the work, keep it.
`;

const PATTERNS_MD = `${marker()}

# Patterns

Distilled from the articles I saved. **This file is regenerated** by the
"Swipe Digest" Mission Control section from my Obsidian \`Clippings/\` folder —
edits below the line will be overwritten. Add your own notes above the line.

---

## Starter patterns (used until the swipe file has enough material)

These are defaults, not evidence. They get replaced by patterns actually
observed in saved articles once \`Clippings/\` has some.

### Title shapes that earn a click

1. **How I <did the hard thing>** — the plain build story.
   "How I integrated Grok into CloudCLI"
2. **How I built <thing> to <escape a chore>** — outcome the reader wants.
   "How I built Mission Control so my agents queue their own work"
3. **The <mundane thing> that cost me <real cost>** — a small cause, a big bill.
4. **I was wrong about <belief>** — reversal, stated flatly.
5. **<Number> things that broke when I <did the thing>** — only when the list
   is genuinely surprising; overused and decaying.

Rules: under 70 characters. Concrete noun in the title. No colon-subtitle
construction. No "ultimate", "complete", "definitive".

### Opening moves

- **Cold open on the moment it broke.** State the symptom in one line, before
  any context.
- **State the goal, then the obstacle** in two sentences. Do not explain the
  project first — the reader does not care yet.
- **Lead with the wrong belief.** "I assumed X. That assumption cost me a
  weekend."

Never open with what the product is. Never open with a definition.

### Structure that holds

Setup (why I wanted this) → first attempt → what broke → what was actually
happening → the fix → what it means for you. Roughly 150 / 250 / 300 / 250 /
150 words.

### Pacing

- A concrete detail — a path, a flag, an error — every 150 words or so.
- One code block or image every two to three sections. Never two in a row.
- Section headings are statements, not labels. "The config was being inherited"
  beats "Investigation".
`;

