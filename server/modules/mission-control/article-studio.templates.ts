const SKILL_STORY_ANGLES = `---
name: story-angles
description: Turn a thing I built into a story with an arc. Use before drafting, to pick the angle and check the story is worth telling at all.
---

${marker()}

# Story angles

A build only becomes an article when it has **tension**. Something had to be
uncertain, wrong, or harder than expected. Find that, or find another story.

## Step 1 — find the tension

Read the build history (Obsidian \`Projects/CloudCLI/Decisions\`, \`Entities\`,
\`Sessions\`, and the repo). For each candidate, answer:

- What did I want that I could not have at the start?
- What did I believe that turned out to be false?
- What did I try first, and why did it fail?
- What did it cost — hours, a weekend, a rewrite?
- What surprised me?

**If three or more answers are blank, this is not a story.** Say so and move on
rather than padding a changelog into an article.

## Step 2 — pick the angle

Same build, different articles. Choose the one with the widest door:

- **The build story.** "How I integrated Grok into CloudCLI." Works when the
  thing itself is desirable and the path was non-obvious.
- **The reversal.** "I thought each CLI was isolated. It wasn't." Works when a
  belief broke. Strongest angle when available.
- **The escape.** "How I stopped hand-triaging my own backlog." Works when the
  build removed a chore the reader also has.
- **The constraint.** "macOS decided my agent wasn't allowed to do that."
  Works when an external system fought back.

Pick one. An article with two angles has none.

## Step 3 — check the door is wide

Ask: who clicks this who has never heard of CloudCLI?

If the honest answer is "nobody", the angle is too internal. Re-frame around
the general situation — integrating an agent, automating your own work,
fighting a platform — and let CloudCLI be the setting rather than the subject.

## Step 4 — one-line pitch

Write the story in one sentence before drafting: "I wanted X, assumed Y, hit Z,
and what actually fixed it was W."

If that sentence is boring, the article will be boring. Go back to step 1.
`;

const SKILL_HOOKS_AND_TITLES = `---
name: hooks-and-titles
description: Write the title and the first three lines. Use after the angle is chosen — these decide whether anything else gets read.
---

${marker()}

# Hooks and titles

Read \`patterns/patterns.md\` first. Those patterns come from articles that
actually performed; the guidance here is how to apply them.

## Titles

Write **five**, then pick. Never ship the first one.

Requirements:
- Under 70 characters.
- A concrete noun from the actual story — the provider, the file, the platform.
- Says what happened, not what the article covers.
- No colon-subtitle. No "ultimate/complete/definitive/comprehensive".
- Curiosity from specificity, not from withholding. "How I integrated Grok
  into CloudCLI" beats "The one integration that changed everything".

Keep the four runners-up as \`titleVariants\` so I can swap.

## The hook — first three lines

This is the whole game. On x.com the reader sees roughly this much before
deciding.

The hook must:
1. Open on a concrete moment, not context. A symptom, a decision, a cost.
2. Contain one specific, checkable detail in the first sentence.
3. Create a question the next paragraph answers.

Do not: introduce the project, define a term, set the scene, or say what the
article will cover.

**Weak:** "CloudCLI is a multi-agent CLI workspace. Recently I decided to add
support for Grok, which turned out to be interesting."

**Strong:** "Grok had been running in CloudCLI for about ten minutes before I
noticed it had quietly loaded every MCP server I'd configured for Claude."

## Promo thread

The first tweet is the hook, unchanged. Then one tweet per beat of the story —
not a summary, a compression. The last tweet points at the article.

Each tweet must survive alone. No "1/" cliffhangers that say nothing.
`;

const SKILL_ARTICLE_STRUCTURE = `---
name: article-structure
description: Shape the middle of the article so it keeps being read. Use while drafting, and again when cutting.
---

${marker()}

# Article structure

## The arc

1. **The want** (~150 words) — what I was trying to do, and why it mattered
   enough to spend a weekend on. Personal stakes, not product benefits.
2. **The first attempt** (~250) — what I tried, why it was reasonable. The
   reader should agree with the wrong approach.
3. **The break** (~300) — what actually happened. Real error strings, real
   paths. The most concrete section in the article.
4. **The real cause** (~250) — what was going on underneath. This is the payoff.
5. **The fix** (~200) — what I changed. Code here, but only the interesting
   lines.
6. **What it means for you** (~150) — the transferable lesson. Short. Do not
   restate the article.

900–1400 words total. Longer is not better.

## Headings

Statements, sentence case, no numbering. A reader who only skims the headings
should get the story.

- Good: "The config was being inherited from another CLI"
- Bad: "Root cause analysis"

## Concreteness budget

A specific, checkable detail every ~150 words: a path, a flag, an error, a
duration, a version. Sections without one are where readers leave.

## Code

Only when the code *is* the point. Under 22 lines, real, reduced but not
invented. Introduce what to notice **before** the block, not after — nobody
reads code then goes back for the explanation.

## Cutting

Cut last, and cut hard. Remove:
- Any sentence explaining what you are about to explain.
- Any paragraph that would survive in the product docs.
- The conclusion, if it restates the article.
- Adverbs doing the work a fact should do ("surprisingly", "incredibly").

A draft that loses 20% in the cut is a better draft.
`;

const SKILL_FACT_GROUNDING = `---
name: fact-grounding
description: Pull real, checkable detail out of Obsidian and the repo without turning the article into documentation. Use while drafting and before finalising.
---

${marker()}

# Fact grounding

The story is the reason to read; the facts are the reason to believe. Get them
right, and keep them subordinate to the narrative.

## Where things are

- **What happened and why:** Obsidian, \`Projects/CloudCLI/\` —
  \`Decisions/\` (a choice and its reason), \`Entities/\` (subsystems and their
  sharp edges), \`Sessions/\` (dated logs; the debugging narrative and the
  error strings live here).
- **What the code does:** the repo at \`~/Development/cloudcli-fork\`.
- **When it happened:** session note filenames are dated.

## Rules

1. **Never invent.** Not a feature, not a number, not a date, not an error
   string. If it is not written down, either leave it out or say plainly that
   you do not remember.
2. **Every specific claim gets a source.** Record it in \`factCheck\` with the
   vault or repo path that backs it.
3. **No measurement without a measurement.** "Faster" is fine. "3x faster"
   needs a recorded number.
4. **Dates from the notes**, not from guessing.
5. Prefer the *smallest* true detail. "A 24-character Trello id" is better than
   "an identifier mismatch".

## Turning a fact into narrative

Do not write: "The \`compat.claude.mcps\` flag defaults to true, causing Grok
to import \`~/.claude.json\`."

Write: "Grok was reading \`~/.claude.json\` on startup. Not because I told it
to — because \`compat.claude.mcps\` defaults to true, and I had never looked."

Same fact. The second one has a person in it.
`;

const SKILL_SWIPE_ANALYSIS = `---
name: swipe-analysis
description: Distill saved articles from the Obsidian Clippings folder into reusable title, hook and structure patterns. Use for the Swipe Digest run that regenerates patterns/patterns.md.
---

${marker()}

# Swipe analysis

Turn a folder of articles I liked into patterns I can reuse. The output is
evidence about what works, not a book report.

## Input

Obsidian folder \`Clippings/\` — articles saved with Obsidian Web Clipper.
Read them with the obsidian tools. Prefer recent clippings; ignore anything
that is obviously a product page, changelog, or reference doc rather than a
written piece.

## What to extract per article

For each, note only:
- The **title shape**, abstracted: "How I <verb> <thing>", "The <small thing>
  that <big consequence>". Not the title itself.
- The **opening move**: how the first three lines earn the fourth. Cold open on
  a symptom? A stated belief? A number?
- The **structure**: the beats, in order, with rough proportions.
- One **technique worth stealing** — a transition, a way of handling code, a
  way of admitting error.

Skip anything about topic or subject matter. I am not copying what they wrote
about, only how they built it.

## What to output

Rewrite \`patterns/patterns.md\` below its \`---\` divider. Keep everything above
the divider untouched — those are my own notes.

Structure the output as:
1. **Title shapes** — ranked by how often they appear, each with one real
   example from the swipe file and a note on when it fits.
2. **Opening moves** — same treatment.
3. **Structures** — the two or three arcs that recur.
4. **Techniques worth stealing** — a short list, each one specific enough to
   act on.
5. **What I notice these have in common** — three to five sentences, honest.
   If the sample is too small or too varied to conclude anything, say that
   instead of inventing a trend.

## Honesty rules

- Patterns must come from articles actually in the folder. Do not pad with
  general writing advice.
- Say how many articles the digest is based on. Under five is a small sample —
  label it as such.
- If two articles contradict each other, record both rather than averaging them
  into mush.
`;

